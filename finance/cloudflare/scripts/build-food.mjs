// Wraps src/food-src.gs (the Food Arrangement Apps Script, unchanged) into an ES module that runs inside the Worker.
// The Apps Script services it uses (sheets, cache, properties, fetch ...) are passed in as parameters (src/food.js supplies them).
import fs from 'node:fs';
const dir = new URL('../src/', import.meta.url);
let src = fs.readFileSync(new URL('food-src.gs', dir), 'utf8');
const m = /FINANCE_API: '[^']*'/;
if (!m.test(src)) throw new Error('FINANCE_API not found');
src = src.replace(m, "FINANCE_API: 'internal:finance'");                     // Finance runs in the same Worker: no network hop
const body = '/* GENERATED by scripts/build-food.mjs from src/food-src.gs - do not edit */\n' +
  'export function makeFood(SpreadsheetApp, CacheService, PropertiesService, LockService, Utilities, UrlFetchApp, ContentService, ScriptApp) {\n' +
  src + '\n  return { HANDLERS_: HANDLERS_, tick: tick, fx_: fx_, SP: SP };\n}\n';
fs.writeFileSync(new URL('food-core.js', dir), body);
console.log('food-core.js', body.length);
